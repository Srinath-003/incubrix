import re
from typing import Any, Dict, List
from pydantic import BaseModel, Field

from app.models.common import Destination, Rendition


class PolicyCheckResult(BaseModel):
    """Result of pre-publish policy validation."""

    ok: bool = True
    violations: List[str] = Field(default_factory=list)


class PolicyEngine:
    """Pre-publish policy validation hook enforcing destination rules.
    
    Supports:
      1. Destination frequency caps
      2. Self-promotion restrictions
      3. Link restrictions
      4. AI disclosure requirements
    """

    SELF_PROMO_PATTERNS = [
        r"\bbuy now\b",
        r"\bspecial discount\b",
        r"\bpromo code\b",
        r"\baffiliate link\b",
        r"\bsubscribe to my\b",
        r"\blimited time offer\b",
        r"\bcash prize\b",
        r"\bclick link in bio\b",
    ]

    AI_DISCLOSURE_MARKERS = [
        "#ai",
        "#aigenerated",
        "#aiart",
        "ai-generated",
        "[ai]",
        "(ai generated)",
        "generated by ai",
    ]

    @classmethod
    def evaluate(
        cls,
        rendition: Rendition | Dict[str, Any],
        destination: Destination | Dict[str, Any],
    ) -> PolicyCheckResult:
        """Evaluate rendition against destination policy settings."""
        violations: List[str] = []

        rend_dict = rendition.model_dump() if isinstance(rendition, Rendition) else rendition
        dest_dict = destination.model_dump() if isinstance(destination, Destination) else destination
        dest_settings = dest_dict.get("settings", {})

        title = (rend_dict.get("title") or "").strip()
        caption = (rend_dict.get("caption") or "").strip()
        combined_text = f"{title} {caption}".lower()
        tags = [str(t).lower() for t in rend_dict.get("tags", [])]
        extra = rend_dict.get("extra", {})

        # 1. Destination frequency caps
        if dest_settings.get("frequency_cap_exceeded") is True:
            violations.append("Destination frequency cap exceeded: destination is temporarily rate-limited")

        # 2. Self-promotion restrictions
        if dest_settings.get("prohibit_self_promotion") is True:
            for pattern in cls.SELF_PROMO_PATTERNS:
                if re.search(pattern, combined_text, re.IGNORECASE):
                    violations.append(
                        f"Self-promotion restriction violated: content matches prohibited promotional pattern '{pattern}'"
                    )
                    break

        # 3. Link restrictions
        prohibit_links = dest_settings.get("prohibit_links") is True
        max_links = dest_settings.get("max_links")
        links = re.findall(r"https?://[^\s]+", f"{title} {caption}")
        if prohibit_links and len(links) > 0:
            violations.append(
                f"Link restriction violated: destination prohibits external URLs ({len(links)} found)"
            )
        elif max_links is not None and len(links) > max_links:
            violations.append(
                f"Link restriction violated: found {len(links)} links, maximum permitted is {max_links}"
            )

        # 4. AI disclosure requirements
        requires_ai = dest_settings.get("require_ai_disclosure") is True
        is_ai_content = (
            extra.get("is_ai_generated") is True
            or extra.get("ai_generated") is True
            or any("ai" in t for t in tags)
        )
        if requires_ai and is_ai_content:
            has_disclosure = any(m in combined_text for m in cls.AI_DISCLOSURE_MARKERS) or any(
                t in ("#ai", "ai", "aigenerated", "aiart") for t in tags
            )
            if not has_disclosure:
                violations.append(
                    "AI disclosure required: content is marked as AI-generated but lacks required disclosure marker (e.g. #ai or [AI])"
                )

        return PolicyCheckResult(ok=len(violations) == 0, violations=violations)
